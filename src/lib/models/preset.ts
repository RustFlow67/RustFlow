import type { UserOwnedRecord } from "./common";

/**
 * Модель пресета железа (presets) — готовые референсные сборки с замерами
 * и настройками Rust для копирования и сравнения.
 */

export type PresetTier = "budget" | "sweetspot" | "mid-high" | "flagship";
export type PresetResolution = "1080p" | "1440p" | "4k";

export const PRESET_TIER_LABEL: Record<PresetTier, string> = {
  budget: "Бюджет",
  sweetspot: "Оптимум",
  "mid-high": "Продвинутый",
  flagship: "Флагман",
};

export interface PresetSettingsSummary {
  graphicsQuality: string;
  drawDistance: number;
  shadowCascades: string;
  shadowQuality: number;
  waterQuality: number;
  shaderLevel: number;
  treeQuality: number;
  maxGibs: number;
  upscaler: string;
  reflexOrAntiLag: string;
  gcBuffer: number;
}

export interface HardwarePreset extends UserOwnedRecord {
  slug: string;
  title: string;
  badge: string;
  featured?: boolean;
  tier: PresetTier;
  priceOrder: number;
  cpuId: string;
  cpu: string;
  gpuId: string;
  gpu: string;
  vramGb: number;
  ram: string;
  ramGb: number;
  ramMhz: number;
  ramCl: number;
  storageId: "hdd" | "sata" | "nvme";
  storage: string;
  resolution: PresetResolution;
  /** Диапазон среднего FPS на моддед-сервере 2x (ориентир по замерам). */
  fpsModded: [number, number];
  /** Диапазон среднего FPS на официальном сервере с высоким онлайном. */
  fpsOfficial: [number, number];
  low1Modded: number;
  low1Official: number;
  frametimeModdedMs: number;
  frametimeOfficialMs: number;
  score10: number;
  bottleneckNote: string;
  testScene: string;
  launchOptions: string;
  settings: PresetSettingsSummary;
  cfgText: string;
  keyTweaks: string[];
  driverNote: string;
}

function makeCfg(s: {
  draw: number;
  shadowMode: number;
  shadowQuality: number;
  cascades: number;
  shadowDist: number;
  shader: number;
  water: number;
  refl: number;
  tree: number;
  meshes: number;
  grass: number;
  af: number;
  lodbias: number;
  aa: number;
  gc: number;
  reflex: number;
}): string {
  return [
    `fps.limit "0"`,
    `graphics.vsync "0"`,
    `graphics.screenmode "0"`,
    `graphics.drawdistance "${s.draw}"`,
    `graphics.shadowmode "${s.shadowMode}"`,
    `graphics.shadowquality "${s.shadowQuality}"`,
    `graphics.shadowcascades "${s.cascades}"`,
    `graphics.shadowdistance "${s.shadowDist}"`,
    `graphics.shadowlights "0"`,
    `graphics.shaderlod "${s.shader}"`,
    `graphics.lodbias "${s.lodbias}"`,
    `graphics.af "${s.af}"`,
    `graphics.dof "False"`,
    `graphics.contactshadows "False"`,
    `graphics.grassshadows "False"`,
    `graphics.reflexmode "${s.reflex}"`,
    `water.quality "${s.water}"`,
    `water.reflections "${s.refl}"`,
    `tree.quality "${s.tree}"`,
    `tree.meshes "${s.meshes}"`,
    `grass.quality "${s.grass}"`,
    `grass.displacement "False"`,
    `effects.antialiasing "${s.aa}"`,
    `effects.ao "False"`,
    `effects.bloom "False"`,
    `effects.motionblur "False"`,
    `effects.shafts "False"`,
    `effects.vignet "False"`,
    `effects.sharpen "True"`,
    `effects.maxgibs "0"`,
    `gc.buffer "${s.gc}"`,
  ].join("\n");
}

